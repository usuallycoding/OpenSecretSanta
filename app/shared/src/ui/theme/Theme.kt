/**
 * The app's colours and type, for the light or dark variant that [appearance] and the device's setting call for. With
 * dynamic colours on and available (Android 12 and later) the wallpaper's colours replace the app's palette.
 */
@Composable
fun AppTheme(
    appearance: Appearance = Appearance(),
    content: @Composable () -> Unit,
) {
    val dark = useDarkTheme(appearance.mode, systemDark = isSystemInDarkTheme())
    val colorScheme: ColorScheme = (if (appearance.dynamicColor && dynamicColorSupported) dynamicColorScheme(dark) else null)
        ?: if (dark) darkScheme else lightScheme

    MaterialTheme(
        colorScheme = colorScheme,
        typography = AppTypography,
        content = content,
    )
}
